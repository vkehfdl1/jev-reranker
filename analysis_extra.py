"""Extra post-hoc analyses on the final-table runs (no API calls).

  python analysis_extra.py  -> results_final/ANALYSIS.md

A. shape of the scores each decision mode returns (support size, ties, mass)
B. request size vs the vendor's ~32,000-byte long-context threshold, tokens and cost anatomy
C. rank fusion (RRF, k=60) of pairs of systems, with paired bootstrap vs the better member
"""
import json
from pathlib import Path

import numpy as np

import final_table as F
import metrics as M

OUT = Path("results_final")
DECISION = ["jevnoul14", "jev14", "lunanoul", "luna"]
MODE = {"jev14": "choice", "luna": "choice", "jevnoul14": "noul", "lunanoul": "noul"}


def load(ds, system):
    return {r["qid"]: r for r in F.read(ds.path_fn(system)) if "error" not in r}


def shape_stats(ds, recs_by_sys, positives):
    rows = []
    for s in DECISION:
        recs = recs_by_sys[s]
        nz, distinct, tie_frac, mass, top1, sup_rec, sup_prec = [], [], [], [], [], [], []
        for qid, r in recs.items():
            sc = r["scores"]
            vals = list(sc.values())
            pos = positives[qid]
            support = {d for d, v in sc.items() if v > 0}
            nz.append(len(support))
            distinct.append(len(set(vals)))
            tie_frac.append(1 - len(set(vals)) / len(vals))
            mass.append(sum(vals))
            top1.append(max(vals))
            sup_rec.append(len(support & pos) / len(pos))
            sup_prec.append(len(support & pos) / len(support) if support else 0.0)
        rows.append((s, np.mean(nz), np.mean(distinct), np.mean(mass), np.mean(top1),
                     np.mean(sup_rec), np.mean(sup_prec)))
    return rows


def size_stats(ds, texts_of, recs_by_sys):
    by = [sum(len(t.encode("utf-8")) for t in texts_of[q]) for q in sorted(texts_of)]
    L = {"mean_kb": np.mean(by) / 1000, "p50_kb": np.median(by) / 1000,
         "p99_kb": np.percentile(by, 99) / 1000, "share_over_32000": float(np.mean(np.array(by) > 32_000))}
    tok = {}
    for s in F.SYSTEMS:
        recs = list(recs_by_sys[s].values())
        t = [r.get("tokens") or 0 for r in recs]
        c = [r.get("cost_usd") or 0 for r in recs]
        tok[s] = (np.mean(t), np.mean(c) * 1000, (sum(c) / sum(t) * 1e6) if sum(t) else None)
    return L, tok


def rrf(rankings, k=60):
    score = {}
    for ranked in rankings:
        for i, d in enumerate(ranked):
            score[d] = score.get(d, 0.0) + 1.0 / (k + i + 1)
    return [d for d, _ in sorted(score.items(), key=lambda x: -x[1])]


def fusion(ds, recs_by_sys, qids, idx):
    pairs = [("jevnoul14", "cohere"), ("jevnoul14", "cohere35"), ("jev14", "cohere"),
             ("jevnoul14", "jev14"), ("jevnoul14", "lunanoul"), ("cohere", "cohere35")]
    base = {s: np.array([M.score_ranking([ds.qrels[q][d] for d in recs_by_sys[s][q]["ranked"]])["ndcg@10"]
                         for q in qids]) for s in F.SYSTEMS}
    out = []
    for a, b in pairs:
        fused = np.array([M.score_ranking([ds.qrels[q][d] for d in rrf([recs_by_sys[a][q]["ranked"],
                                                                        recs_by_sys[b][q]["ranked"]])])["ndcg@10"]
                          for q in qids])
        best = a if base[a].mean() >= base[b].mean() else b
        dv = fused - base[best]
        lo, hi = np.percentile(dv[idx].mean(axis=1), [2.5, 97.5])
        out.append((a, b, base[a].mean(), base[b].mean(), fused.mean(), best, dv.mean(), lo, hi))
    return out


def main():
    (m_ds, m_pres), (j_ds, j_pres) = F.miracl(), F.jqara()
    import data as Dm
    import jqara_data as Dj
    mm, mt = Dm.load_sample()
    jm, jt = Dj.load()
    datasets = []
    # bytes of the passage text actually sent (MIRACL passages are truncated per language)
    m_text = {f"{q['lang']}:{q['qid']}": [mt[f"{q['lang']}:{d}"][:Dm.cap_chars(q["lang"], 100)]
                                          for d in q["pool"][:100]] for q in mm["queries"]}
    j_text = {q["qid"]: [jt[d] for d in q["pool"]] for q in jm["queries"]}
    datasets = [(m_ds, m_text), (j_ds, j_text)]

    L = ["# Extra analyses on the final-table runs\n",
         "Post-hoc, no new API calls. Generated by `analysis_extra.py`.\n"]
    for ds, text in datasets:
        recs_by_sys = {s: load(ds, s) for s in F.SYSTEMS}
        qids = sorted(ds.qrels)
        positives = {q: {d for d, v in ds.qrels[q].items() if v > 0} for q in qids}
        L.append(f"\n## {ds.name}\n")
        L.append("### A. Score shape of the decision modes (per query, mean over queries)\n")
        L.append("`support` = candidates with score > 0; `mass` = sum of scores over the 100 candidates; "
                 "`ties` = 1 − distinct/100; support recall/precision are w.r.t. qrel positives.\n")
        L += ["| system | mode | support size | distinct scores | ties | mass | top-1 score | support recall | support precision | positives/query |",
              "|" + "---|" * 10]
        npos = np.mean([len(p) for p in positives.values()])
        for s, nz, dist, mass, top1, srec, sprec in shape_stats(ds, recs_by_sys, positives):
            tie = 1 - dist / 100
            L.append(f"| {F.LABEL[s]} | {MODE[s]} | {nz:.1f} | {dist:.1f} | {tie:.2f} | {mass:.1f} "
                     f"| {top1:.2f} | {srec:.2f} | {sprec:.2f} | {npos:.1f} |")
        size, tok = size_stats(ds, text, recs_by_sys)
        L.append("\n### B. Request size and billing\n")
        L.append(f"Passage text per query (UTF-8): mean {size['mean_kb']:.1f} KB, p50 {size['p50_kb']:.1f} KB, "
                 f"p99 {size['p99_kb']:.1f} KB; **{size['share_over_32000']*100:.0f}% of queries exceed 32,000 bytes** "
                 "(the threshold above which OpenRouter's Jev guide says requests run in TypeSafe's slower, "
                 "less accurate long-context mode; vendor claim, not verified here).\n")
        L += ["| system | input tokens / query | $ / 1K queries | implied $ / M tokens |", "|---|---|---|---|"]
        for s in F.SYSTEMS:
            t, c, per_m = tok[s]
            L.append(f"| {F.LABEL[s]} | {t:,.0f} | {c:.3f} | {('%.3f' % per_m) if per_m else 'per search unit'} |")
        common = [q for q in qids if all(q in recs_by_sys[s] for s in F.SYSTEMS)]
        rng = np.random.default_rng(0)
        idx = rng.integers(0, len(common), size=(10_000, len(common)))
        L.append(f"\n### C. Rank fusion (RRF, k=60) of two systems — nDCG@10 "
                 f"({len(common)} queries answered by every system)\n")
        L += ["| a + b | a | b | fused | Δ fused − better of (a, b) [95% CI] |", "|---|---|---|---|---|"]
        for a, b, na, nb, nf, best, d, lo, hi in fusion(ds, recs_by_sys, common, idx):
            L.append(f"| {a} + {b} | {na:.4f} | {nb:.4f} | {nf:.4f} | {d:+.4f} [{lo:+.4f}, {hi:+.4f}] |")
    (OUT / "ANALYSIS.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
